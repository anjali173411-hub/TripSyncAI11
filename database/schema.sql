-- Planora database schema for MySQL 8.0.16+
-- Run with:  mysql -u root -p < database/schema.sql
--
-- Everything is stored here in MySQL,
-- EXCEPT the AI-generated itinerary, which is stored in MongoDB.
--
-- WARNING: this starts the database fresh (old test data is removed).

DROP DATABASE IF EXISTS planora;

CREATE DATABASE planora
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE planora;

-- ===== Users (Module 3.1) =====
CREATE TABLE users (
  id                INT           NOT NULL AUTO_INCREMENT,
  name              VARCHAR(100)  NOT NULL,
  email             VARCHAR(150)  NOT NULL UNIQUE,
  password          VARCHAR(255)  NOT NULL,                  -- scrambled with bcrypt
  role              VARCHAR(20)   NOT NULL DEFAULT 'traveller', -- traveller or admin
  default_interests JSON          NULL,                      -- e.g. ["Food","Nature"]
  default_pace      VARCHAR(20)   NOT NULL DEFAULT 'balanced',
  is_active         BOOLEAN       NOT NULL DEFAULT TRUE,
  token_version     INT           NOT NULL DEFAULT 0,        -- goes up on logout
  created_at        DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);

-- ===== Trips (Module 3.2) — same columns as before, plus owner, type and trip_status =====
CREATE TABLE trips (
  id               CHAR(36)      NOT NULL,             -- UUID generated by the backend
  title            VARCHAR(120)  NULL,                 -- trip name, e.g. "Goa with college friends"
  owner_id         INT           NOT NULL,             -- the organiser
  type             VARCHAR(10)   NOT NULL DEFAULT 'solo',     -- solo or group
  trip_status      VARCHAR(20)   NOT NULL DEFAULT 'planning', -- planning, finalised, completed
  destination      VARCHAR(150)  NULL,
  start_location   VARCHAR(150)  NOT NULL,
  start_date       DATE          NOT NULL,
  end_date         DATE          NOT NULL,
  budget           DECIMAL(12,2) NOT NULL,
  travellers       INT           NOT NULL,
  preference_text  TEXT          NOT NULL,
  status           VARCHAR(30)   NOT NULL DEFAULT 'draft',    -- AI plan: draft, ready, generation_failed
  generation_error TEXT          NULL,
  created_at       DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at       DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT chk_budget          CHECK (budget > 0),
  CONSTRAINT chk_travellers      CHECK (travellers BETWEEN 1 AND 50),
  CONSTRAINT chk_preference_text CHECK (CHAR_LENGTH(TRIM(preference_text)) >= 10),
  CONSTRAINT chk_valid_dates     CHECK (end_date >= start_date)
);

-- Who is on each trip (the organiser is a member too)
CREATE TABLE trip_members (
  trip_id CHAR(36) NOT NULL,
  user_id INT      NOT NULL,
  PRIMARY KEY (trip_id, user_id),
  FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Invitations to group trips (FR-2.3, FR-2.4)
CREATE TABLE invitations (
  id      INT         NOT NULL AUTO_INCREMENT,
  trip_id CHAR(36)    NOT NULL,
  user_id INT         NOT NULL,
  status  VARCHAR(20) NOT NULL DEFAULT 'pending', -- pending, accepted, declined
  PRIMARY KEY (id),
  FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ===== Preferences: one per person, per trip (Module 3.3) =====
CREATE TABLE preferences (
  id                  INT           NOT NULL AUTO_INCREMENT,
  trip_id             CHAR(36)      NOT NULL,
  user_id             INT           NOT NULL,
  interests           JSON          NULL,
  pace                VARCHAR(20)   NOT NULL DEFAULT 'balanced',
  budget_contribution DECIMAL(12,2) NOT NULL DEFAULT 0,
  must_do             JSON          NULL,
  deal_breakers       JSON          NULL,
  notes               TEXT          NULL,
  PRIMARY KEY (id),
  UNIQUE KEY one_per_person (trip_id, user_id),
  FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ===== Clashes found by the AI, and votes (Module 3.5) =====
CREATE TABLE conflicts (
  id                INT          NOT NULL AUTO_INCREMENT,
  trip_id           CHAR(36)     NOT NULL,
  description       TEXT         NOT NULL,
  reasoning         TEXT         NULL,
  options           JSON         NOT NULL,     -- the compromises to vote on
  resolved          BOOLEAN      NOT NULL DEFAULT FALSE,
  selected_option   INT          NULL,
  custom_resolution TEXT         NULL,         -- organiser's own decision
  resolved_by       VARCHAR(20)  NULL,         -- vote or organiser
  created_at        DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE
);

-- Which members are involved in each clash
CREATE TABLE conflict_members (
  conflict_id INT NOT NULL,
  user_id     INT NOT NULL,
  PRIMARY KEY (conflict_id, user_id),
  FOREIGN KEY (conflict_id) REFERENCES conflicts(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- One vote per member per clash
CREATE TABLE votes (
  conflict_id  INT NOT NULL,
  user_id      INT NOT NULL,
  option_index INT NOT NULL,
  PRIMARY KEY (conflict_id, user_id),
  FOREIGN KEY (conflict_id) REFERENCES conflicts(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ===== Expenses (Module 3.7) =====
CREATE TABLE expenses (
  id          INT           NOT NULL AUTO_INCREMENT,
  trip_id     CHAR(36)      NOT NULL,
  category    VARCHAR(50)   NOT NULL,
  amount      DECIMAL(12,2) NOT NULL,
  kind        VARCHAR(10)   NOT NULL DEFAULT 'actual', -- planned or actual
  paid_by     INT           NULL,
  description VARCHAR(255)  NOT NULL DEFAULT '',
  created_by  INT           NOT NULL,
  created_at  DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE,
  FOREIGN KEY (paid_by) REFERENCES users(id) ON DELETE SET NULL,
  FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT chk_amount CHECK (amount > 0)
);

-- ===== Destinations and reviews (Module 3.9) =====
CREATE TABLE destinations (
  id             INT           NOT NULL AUTO_INCREMENT,
  name           VARCHAR(100)  NOT NULL,
  region         VARCHAR(100)  NOT NULL DEFAULT '',
  description    TEXT          NULL,
  average_cost   DECIMAL(12,2) NOT NULL DEFAULT 0,
  images         JSON          NULL,                       -- list of picture links
  cost_tier      VARCHAR(20)   NOT NULL DEFAULT 'mid-range', -- budget, mid-range or luxury
  average_rating DECIMAL(3,1)  NOT NULL DEFAULT 0,
  PRIMARY KEY (id)
);

CREATE TABLE reviews (
  id             INT       NOT NULL AUTO_INCREMENT,
  destination_id INT       NOT NULL,
  user_id        INT       NOT NULL,
  rating         INT       NOT NULL,
  comment        TEXT      NULL,
  visible        BOOLEAN   NOT NULL DEFAULT TRUE, -- false = hidden by admin
  created_at     DATETIME  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY one_review_each (destination_id, user_id),
  FOREIGN KEY (destination_id) REFERENCES destinations(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT chk_rating CHECK (rating BETWEEN 1 AND 5)
);

